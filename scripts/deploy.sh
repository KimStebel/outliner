#!/usr/bin/env bash
#
# Build and push the app to the production server.
#
# Credentials come from ./prod-env (gitignored), which holds:
#   ip: <address>
#   user: <user>
#   password: <password>
#
# The identity provider's own secrets live in ./prod-rauthy-env and the single
# account's password in ./prod-rauthy-user, both also gitignored and both
# generated here on the first run. Do not regenerate prod-rauthy-env: the
# provider's database is encrypted with those keys.
#
# Usage: ./scripts/deploy.sh [--first-run]
#
# --first-run generates the identity provider's secrets and the account
# password. Only correct when there is no Rauthy database yet: bootstrap data
# is applied to an empty database and nothing else, so generating these against
# a live deployment produces credentials that silently do not work.

set -euo pipefail

cd "$(dirname "$0")/.."

ENV_FILE=prod-env
# The identity provider's secrets, and the single account's password. Both
# generated below if absent, then left alone.
RAUTHY_ENV=prod-rauthy-env
RAUTHY_USER=prod-rauthy-user
# Cloudflare R2, for backups. Written by hand, holding:
#   accountId: <id>
#   key: <access key id>
#   secret: <secret access key>
R2_FILE=prod-cloudflare-r2
R2_BUCKET=outliner-backups

# Generating a secret is only ever right for a deployment that does not exist
# yet, so it takes an explicit flag.
#
# Without this, a missing file was silently replaced with a fresh one — which
# is a trap, because Rauthy applies bootstrap data only to an empty database.
# A regenerated prod-rauthy-user therefore holds a password that was never set
# and will not work, while claiming to be the password; and a regenerated
# prod-rauthy-env holds encryption keys that cannot read the existing
# database at all. Both failures are silent at deploy time.
#
# Moving these into a password manager and deleting the local copies — which
# is exactly what the backup notes tell you to do — is enough to trigger it.
FIRST_RUN=false
if [[ "${1:-}" == "--first-run" ]]; then
  FIRST_RUN=true
fi

for required in "$ENV_FILE" "$R2_FILE"; do
  if [[ ! -f $required ]]; then
    echo "Missing $required." >&2
    exit 1
  fi
done

if [[ $FIRST_RUN == false ]]; then
  for required in "$RAUTHY_ENV"; do
    if [[ ! -f $required ]]; then
      cat >&2 <<MISSING
Missing $required.

Restore it from your password manager. Do not let it be regenerated: these
only take effect when Rauthy initialises an empty database, so a new one
would not match what is deployed — a new password would simply not work, and
new encryption keys could not read the existing database.

If this really is a brand new deployment with no Rauthy database yet:
  ./scripts/deploy.sh --first-run
MISSING
      exit 1
    fi
  done
fi

field() { sed -n "s/^$1:[[:space:]]*//p" "$ENV_FILE" | head -1; }

HOST=$(field ip)
USER=$(field user)
# Exported, not passed on a command line, so it never shows up in `ps`.
SSHPASS=$(field password)
export SSHPASS

# Under /home deliberately. Docker on this server is the Canonical snap, and
# snap confinement grants it the `home` interface only — from /opt it cannot
# read the compose file, and the daemon cannot bind-mount the site directory.
REMOTE_DIR=/home/outliner
SSH_OPTS=(-o StrictHostKeyChecking=accept-new -o ConnectTimeout=15)

# -- the identity provider's secrets -----------------------------------------

# Generated once and then never touched: the encryption keys are what the
# stored data is encrypted with, so rotating them would make the existing
# database unreadable and lose the account.
#
# No `$` in any value, deliberately. Compose interpolates env_file values, and
# that is what mangled the bcrypt hash when the basic-auth credentials were
# passed this way.
rand() { head -c "$1" /dev/urandom | base64 -w0 | tr -d '/+=' | head -c "$2"; }

# The encryption key is different: it has to be real base64 of exactly 32
# bytes, so it cannot be squeezed through `rand` — stripping characters out of
# a base64 string does not leave a shorter base64 string, it leaves something
# that does not decode, which is how the first attempt at this produced a key
# Rauthy rejected outright with "Invalid ENC_KEYS".
#
# Generated until it happens to contain no `/` or `+`: the key is written as
# `id/key`, so a `/` inside it would make the separator ambiguous. Takes a
# handful of tries.
enc_key() {
  local key
  while :; do
    key=$(head -c 32 /dev/urandom | base64 -w0)
    if [[ $key != */* && $key != *+* ]]; then
      # Cheap proof it is what it claims to be, rather than finding out from a
      # panic in a container log.
      if [[ $(printf '%s' "$key" | base64 -d 2>/dev/null | wc -c) -eq 32 ]]; then
        printf '%s' "$key"
        return
      fi
    fi
  done
}

if [[ ! -f $RAUTHY_ENV ]]; then
  echo "==> Generating $RAUTHY_ENV (keep this file; put it in your password manager)"
  umask 077
  key_id=$(rand 16 8)
  cat >"$RAUTHY_ENV" <<ENVEOF
# Rauthy's secrets for outliner.stebel.kim. Generated by scripts/deploy.sh.
#
# Do not regenerate these: the database is encrypted with ENC_KEYS, and a new
# key makes the existing account and signing keys unreadable.
ENC_KEYS=$key_id/$(enc_key)
ENC_KEY_ACTIVE=$key_id
HQL_SECRET_RAFT=$(rand 48 32)
HQL_SECRET_API=$(rand 48 32)
BOOTSTRAP_ADMIN_EMAIL=admin@stebel.kim
BOOTSTRAP_ADMIN_PASSWORD_PLAIN=$(rand 32 24)
ENVEOF
fi

if [[ $FIRST_RUN == true && ! -f $RAUTHY_USER ]]; then
  echo "==> Generating $RAUTHY_USER (keep this file; put it in your password manager)"
  umask 077
  printf 'kim.stebel@gmail.com:%s\n' "$(rand 32 24)" >"$RAUTHY_USER"
fi

if grep -q '[$]' "$RAUTHY_ENV"; then
  echo "$RAUTHY_ENV contains a dollar sign, which compose would mangle." >&2
  exit 1
fi

# Placed where the compose file expects it, so the same file works on both
# sides and the configuration below can be validated against it locally.
cp "$RAUTHY_ENV" deploy/rauthy.env
chmod 600 deploy/rauthy.env

# The R2 credentials, in the shape Rauthy wants them. backup-doc.sh sources
# this same file, so there is one copy of the credentials on the server rather
# than one per consumer.
r2_field() { sed -n "s/^$1:[[:space:]]*//p" "$R2_FILE" | head -1; }
(
  umask 077
  cat >deploy/r2.env <<R2EOF
HQL_S3_URL=https://$(r2_field accountId).r2.cloudflarestorage.com
HQL_S3_BUCKET=$R2_BUCKET
HQL_S3_REGION=auto
HQL_S3_PATH_STYLE=true
HQL_S3_KEY=$(r2_field key)
HQL_S3_SECRET=$(r2_field secret)
R2EOF
)

# -- validate the provider's configuration before shipping it ----------------

# Rauthy validates its own config and panics on anything it does not like.
# Doing that here rather than discovering it from a container log on the
# server: two deploys were spent learning that ENC_KEYS has to be real base64
# and that rp_origin needs an explicit port, both of which this catches.
#
# It also reaches R2 to test the connection, so bad backup credentials fail
# here rather than at half past two in the morning.
#
# Run through compose so it uses exactly the production environment, rather
# than a second copy of it that could drift.
echo "==> Validating the provider's configuration"
docker compose -f deploy/docker-compose.yml run --rm --no-deps \
  --entrypoint /app/rauthy \
  rauthy validate-config --path /app/config.toml

echo "==> Building"
npm run build

echo "==> Preparing $REMOTE_DIR on $HOST"
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" "mkdir -p $REMOTE_DIR/site"

echo "==> Uploading site"
# --delete so files removed from a build do not linger and get served.
sshpass -e rsync -az --delete \
  -e "ssh ${SSH_OPTS[*]}" \
  dist/ "$USER@$HOST:$REMOTE_DIR/site/"

# -- the provider's bootstrap data -------------------------------------------

# Staged locally so the client definition is the only thing rsynced, rather
# than the whole of deploy/rauthy.
echo "==> Staging Rauthy bootstrap data"
BOOTSTRAP_DIR=deploy/rauthy/bootstrap-prod
rm -rf "$BOOTSTRAP_DIR"
mkdir -p "$BOOTSTRAP_DIR"
cp deploy/rauthy/bootstrap/clients.json "$BOOTSTRAP_DIR/"

# Accounts are not the deploy's business. A routine deploy ships no user at
# all, so it cannot create, replace or disturb one — Rauthy holds them, and
# they are managed in its admin UI at /auth/v1/admin.
#
# On a first run there is no database and no admin UI to reach yet, so the one
# account is seeded here. Its id is pinned, and has to match AUTH_SUBJECTS in
# the compose file: that is what the backend authorises against. A subject id
# is not a secret.
#
# The password is hashed here, with the parameters Rauthy uses, so only the
# hash reaches the server — as was done for the basic-auth credentials.
# Rauthy's own `hash-password` wants a terminal, which a script has not got.
if [[ $FIRST_RUN == true ]]; then
  echo "    including the initial user (first run)"
  USER_EMAIL=$(cut -d: -f1 "$RAUTHY_USER")
  USER_PW=$(cut -d: -f2- "$RAUTHY_USER")
  export USER_PW
  USER_HASH=$(docker run --rm -e USER_PW alpine:3 sh -c '
    apk add -q argon2 >/dev/null 2>&1
    salt=$(head -c 16 /dev/urandom | base64 | tr -d "=+/" | head -c 16)
    printf "%s" "$USER_PW" | argon2 "$salt" -id -t 3 -m 15 -p 2 -e')
  unset USER_PW

  python3 - "$BOOTSTRAP_DIR" "$USER_EMAIL" "$USER_HASH" <<'PY'
import json, sys
directory, email, password_hash = sys.argv[1:4]
json.dump(
    [
        {
            "id": "outlinerkimstebel0000001",
            "email": email,
            "given_name": "Kim",
            "password": {"Argon2ID": password_hash},
            "roles": ["user"],
            "enabled": True,
            "email_verified": True,
        }
    ],
    open(f"{directory}/users.json", "w"),
    indent=2,
)
PY
fi

echo "==> Uploading Caddy config and backend source"
sshpass -e rsync -az \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/Caddyfile deploy/docker-compose.yml "$USER@$HOST:$REMOTE_DIR/"
sshpass -e rsync -az --chmod=F600 \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/rauthy.env "$USER@$HOST:$REMOTE_DIR/rauthy.env"
sshpass -e rsync -az --chmod=F600 \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/r2.env "$USER@$HOST:$REMOTE_DIR/r2.env"
sshpass -e rsync -az --chmod=F700 \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/backup-doc.sh "$USER@$HOST:$REMOTE_DIR/backup-doc.sh"
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" "mkdir -p $REMOTE_DIR/rauthy"
sshpass -e rsync -az \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/rauthy/config.toml "$USER@$HOST:$REMOTE_DIR/rauthy/"
sshpass -e rsync -az --delete --chmod=F600 \
  -e "ssh ${SSH_OPTS[*]}" \
  "$BOOTSTRAP_DIR/" "$USER@$HOST:$REMOTE_DIR/rauthy/bootstrap/"
# Readable by the process that has to read it. Rauthy runs as 10001 and will
# not read a file it has no access to — and says nothing when it cannot, so
# the clients and the user were silently never created the first time this ran.
# Kept at 0600 rather than widened: the file holds a password hash.
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" \
  "chown -R 10001:10001 $REMOTE_DIR/rauthy/bootstrap"
sshpass -e rsync -az --delete \
  --exclude target \
  -e "ssh ${SSH_OPTS[*]}" \
  backend/ "$USER@$HOST:$REMOTE_DIR/backend/"

# The backend runs unprivileged, so its data directory must be writable by it.
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" \
  "mkdir -p $REMOTE_DIR/data && chown -R 10001:10001 $REMOTE_DIR/data"

echo "==> Building and starting"
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" \
  "cd $REMOTE_DIR && docker compose up -d --build"

# The Caddyfile is a bind mount, so changing it does not change the container
# and `up -d` leaves it running with the old config. Without this, a config
# change silently does not take effect.
# -- the backup timer --------------------------------------------------------

# A systemd timer rather than cron, for `Persistent=true`: a run missed while
# the machine was off is caught up on the next boot instead of being skipped.
echo "==> Installing the backup timer"
sshpass -e rsync -az \
  -e "ssh ${SSH_OPTS[*]}" \
  deploy/outliner-backup.service deploy/outliner-backup.timer \
  "$USER@$HOST:/etc/systemd/system/"
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" \
  "systemctl daemon-reload && systemctl enable --now outliner-backup.timer && \
   systemctl list-timers outliner-backup.timer --no-pager | sed -n 2p"

echo "==> Reloading Caddy config"
sshpass -e ssh "${SSH_OPTS[@]}" "$USER@$HOST" \
  "cd $REMOTE_DIR && docker compose exec -T caddy caddy reload --config /etc/caddy/Caddyfile 2>&1 | tail -1 && docker compose ps"

echo "==> Done. https://outliner.stebel.kim"
echo "    Sign in with the account in $RAUTHY_USER."
