/**
 * Emits the service worker at build time.
 *
 * It is generated rather than hand-written because the precache list has to
 * name the real hashed filenames, which only exist once the bundle does. The
 * cache name is derived from that same list, so a build that changes any asset
 * gets a new cache and the old one is dropped on activation.
 */

import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import { join, posix, relative, sep } from 'node:path'
import type { Plugin } from 'vite'

/** Files copied verbatim from `public/`; Vite does not list these in the bundle. */
function publicFiles(root: string): string[] {
  const dir = join(root, 'public')
  const found: string[] = []
  const walk = (current: string): void => {
    for (const entry of readdirSync(current)) {
      const full = join(current, entry)
      if (statSync(full).isDirectory()) walk(full)
      else found.push(`/${relative(dir, full).split(sep).join(posix.sep)}`)
    }
  }
  try {
    walk(dir)
  } catch {
    // No public directory: nothing extra to precache.
  }
  return found
}

export function serviceWorker(): Plugin {
  let root = process.cwd()

  return {
    name: 'outliner-service-worker',
    apply: 'build',

    configResolved(config) {
      root = config.root
    },

    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle).map((file) => `/${file}`)
      // '/' rather than '/index.html': that is the URL a navigation requests,
      // and it is what the fetch handler looks up for the app shell.
      const precache = ['/', ...assets, ...publicFiles(root)]
        .filter((url) => url !== '/index.html' && url !== '/sw.js')
        .sort()

      const version = createHash('sha256')
        .update(precache.join('\n'))
        .digest('hex')
        .slice(0, 12)

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: render(version, precache),
      })
    },
  }
}

function render(version: string, precache: readonly string[]): string {
  return `/* Generated by sw-plugin.ts. Do not edit. */
const CACHE = 'outliner-${version}'
const PRECACHE = ${JSON.stringify(precache, null, 2)}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      // Take over at once. The app ships as a single bundle, so there are no
      // lazily-loaded chunks a running page could fail to find afterwards.
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))),
      )
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET') return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  // The sync API must always go to the network. Caching it would serve a
  // stale document forever while HEAD — which this handler ignores, being
  // GET-only — kept correctly reporting that it had changed.
  if (url.pathname.startsWith('/api/')) return

  // Every route renders the same shell, so a navigation is always answered
  // from cache first. That is what makes a cold start work with no network.
  if (request.mode === 'navigate') {
    event.respondWith(caches.match('/').then((hit) => hit ?? fetch(request)))
    return
  }

  event.respondWith(
    caches.match(request).then((hit) => {
      if (hit !== undefined) return hit
      return fetch(request)
        .then((response) => {
          // Keep anything the precache missed, so it is available next time.
          if (response.ok && response.type === 'basic') {
            const copy = response.clone()
            void caches.open(CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        })
        .catch(() => caches.match('/'))
    }),
  )
})
`
}
